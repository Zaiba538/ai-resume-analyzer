"""M8 Phase 2: canonical report labels are complete, unique, immutable and serialisable."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import get_args

import pytest

from backend.reports import labels
from backend.reports.labels import LABELS, label, labels_as_dict
from backend.schemas.critic import AgentName, Severity
from backend.schemas.interview import LEVELS, InterviewQuestion
from backend.schemas.match import (
    Baseline,
    MatchMetrics,
    SectionCompletenessMetric,
    SkillCoverageMetric,
)
from backend.schemas.report import CriticSummary
from backend.schemas.resume import Education, Experience, ResumeProfile
from backend.schemas.security import FlagType
from backend.schemas.skill_gap import SkillGapReport

SECTIONS_JSON = Path(__file__).resolve().parents[2] / "backend" / "data" / "expected_sections.json"
KEY = re.compile(r"^[a-z][a-z0-9_]*$")
ALL_LABELS = [(group, key, text) for group, items in LABELS.items() for key, text in items.items()]


def _keys(group: str) -> set[str]:
    return set(LABELS[group])


# --- Completeness against the report schemas ---------------------------------


@pytest.mark.parametrize(
    ("group", "expected"),
    [
        ("critic_verdicts", set(get_args(CriticSummary.model_fields["verdict"].annotation))),
        ("severities", set(get_args(Severity))),
        ("agents", set(get_args(AgentName))),
        ("security_flags", set(get_args(FlagType))),
        ("interview_levels", set(LEVELS)),
        ("skill_gap", set(SkillGapReport.model_fields)),
        (
            "resume_sections",
            {s["name"] for s in json.loads(SECTIONS_JSON.read_text("utf-8"))["sections"]},
        ),
    ],
)
def test_value_groups_cover_exactly_the_schema_values(group: str, expected: set[str]) -> None:
    assert expected
    assert _keys(group) == expected


@pytest.mark.parametrize(
    ("group", "fields"),
    [
        ("profile", set(ResumeProfile.model_fields)),
        ("profile", set(Education.model_fields)),
        ("profile", set(Experience.model_fields)),
        ("interview", set(InterviewQuestion.model_fields) - {"id"}),
        ("metrics", set(MatchMetrics.model_fields)),
        ("metrics", set(SkillCoverageMetric.model_fields) - {"value"}),
        ("metrics", set(SectionCompletenessMetric.model_fields) - {"value"}),
        ("baseline", set(Baseline.model_fields)),
    ],
)
def test_field_groups_label_every_displayed_field(group: str, fields: set[str]) -> None:
    assert fields <= _keys(group), fields - _keys(group)


def test_required_sections_and_messages_exist() -> None:
    assert _keys("sections") == {
        "resume_profile",
        "interview_questions",
        "match",
        "baseline",
        "ats_score",
        "skill_gap",
        "critic",
        "security",
    }
    assert {"title", "generated_at", "expires_at"} <= _keys("document")
    assert {"verdict", "issues", "severity", "message", "revisions"} <= _keys("critic")
    assert {"disclaimer", "no_job_description", "security_notice"} <= _keys("messages")
    assert {"not_calibrated", "not_calibrated_note"} <= _keys("ats")


def test_ats_labels_never_present_a_number() -> None:
    assert not any(ch.isdigit() for ch in LABELS["ats"].values())
    assert "score" not in _keys("ats")


def test_disclaimer_states_ai_generated_and_unverified() -> None:
    disclaimer = label("messages", "disclaimer")
    assert "generated by AI" in disclaimer
    assert "not been verified" in disclaimer


# --- Shape: keys and text ----------------------------------------------------


def test_group_and_label_keys_are_stable_identifiers() -> None:
    assert all(KEY.fullmatch(group) for group in LABELS)
    assert all(KEY.fullmatch(key) for _, key, _ in ALL_LABELS)


@pytest.mark.parametrize(("group", "key", "text"), ALL_LABELS)
def test_label_text_is_plain_non_empty_ascii(group: str, key: str, text: str) -> None:
    assert isinstance(text, str)
    assert text and text == text.strip()
    assert text.isascii() and text.isprintable(), f"{group}.{key}"
    assert not set(text) & set("<>&\"'"), f"{group}.{key} contains markup characters"


@pytest.mark.parametrize("group", list(LABELS))
def test_label_texts_are_unique_within_a_group(group: str) -> None:
    texts = list(LABELS[group].values())
    assert len(texts) == len(set(texts))


def test_duplicate_keys_are_rejected() -> None:
    with pytest.raises(ValueError, match="duplicate label key: x"):
        labels._group(("x", "One"), ("x", "Two"))


# --- Immutability and serialisation -----------------------------------------


def test_top_level_mapping_is_read_only() -> None:
    with pytest.raises(TypeError):
        LABELS["extra"] = LABELS["document"]  # type: ignore[index]
    with pytest.raises(TypeError):
        del LABELS["document"]  # type: ignore[attr-defined]


@pytest.mark.parametrize("group", list(LABELS))
def test_groups_are_read_only(group: str) -> None:
    with pytest.raises(TypeError):
        LABELS[group]["title"] = "changed"  # type: ignore[index]
    with pytest.raises(AttributeError):
        LABELS[group].clear()  # type: ignore[attr-defined]


def test_labels_as_dict_is_json_serialisable_and_complete() -> None:
    data = labels_as_dict()
    assert json.loads(json.dumps(data)) == data
    assert data.keys() == LABELS.keys()
    assert all(data[group] == dict(LABELS[group]) for group in LABELS)


def test_labels_as_dict_returns_a_detached_copy() -> None:
    data = labels_as_dict()
    data["document"]["title"] = "changed"
    data.pop("sections")
    assert label("document", "title") == "Resume Analysis Report"
    assert "sections" in LABELS


def test_label_lookup() -> None:
    assert label("critic_verdicts", "revise") == "Needs revision"
    with pytest.raises(KeyError):
        label("critic_verdicts", "unknown")
    with pytest.raises(KeyError):
        label("unknown", "title")


def test_labels_version() -> None:
    assert labels.LABELS_VERSION == 1
